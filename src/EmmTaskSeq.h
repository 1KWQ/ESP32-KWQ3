/**
 * @brief 单条任务的执行阶段（前 6 个对齐 KWQ1 的 `enum TaskPhase`）。
 * @details 前 6 个取值与 KWQ1 保持一致（且已被第二步实机验证过），**不要改动**；
 *          第三步的真实机械动作按"位置"细分，新增的值**一律追加在末尾**
 *          （现为 7 个：`PREAMBLE`/`TRAY_POS`/`DETECT_POS`/`DISCARD_POS`/
 *          `RESET_POS`/`RESTART_SAMPLE`/`PAUSE_PARK`），这样既不影响已有取值，
 *          又能让 `TaskPhaseToStr` 的下标一一对应。
 *
 *          第三步的位置顺序（与用户给的机械流程 Ⅰ~Ⅳ 对应）：
 *          **注意：`TASK_TRAY_POS` 的枚举值排在 `TASK_MOVE_POS` 之后，但实际执行
 *          顺序在它之前**（先转盘、再取样，2026/10/10 方案 A）。
 *
 *            TASK_PREAMBLE   序列前导：**2026/10/19 起不再动电机**（原为
 *                            `SET EMM ZERO A=3` + 2/3 号设单圈零点）。零点只由
 *                            **整机回零**建立，避免把"2 号当前位置"误当零点
 *            TASK_IDLE       进入本条任务（读工位号、点绿灯）
 *            TASK_TRAY_POS   样品盘（4 号）用 MODE=1 绝对位置定位到**本任务**的
 *                            工位（`(N−1)×320`）—— **在取样之前执行**
 *            TASK_MOVE_POS   Ⅱ 取样位：3 号绝对下降到 5000 → 2 号转到取样位正上方
 *                            → 3 号降/慢降 → 抬起（2026/10/14 新流程：改为顺序执行、
 *                            不再 2+3 号同步补偿；且不再停留）
 *            TASK_DETECT_POS Ⅲ 检测位：2 号→检测位 → 3 号降 → 停留 T 分钟 → 3 号抬回安全高度2
 *            TASK_DISCARD_POS Ⅳ 回收位/抛弃位
 *            TASK_RESET_POS  复位：**3 号上升至 2000 → 2 号绝对定位回单圈回零原点
 *                            → 4 号样品盘接近开关回零**
 *                            （**整条队列跑完时只做一次**，用户确认；2026/10/14 新流程：
 *                            取消 4 号样品盘**就近单圈回零** / 2、3 号写回零参数 /
 *                            2+3 号同步回零；2026/10/19：2 号改为绝对定位到 0 + 读回核对，
 *                            并把 4 号回零加回来，改走接近开关重新标定）；
 *                            **2 号回原点失败也不中止**，发 `EVT 306` 后广播停机、
 *                            继续第 3 步、照常收尾、清空队列；
 *                            **4 号回零失败则中止并保留队列**
 *            TASK_RESTART_SAMPLE
 *                            **2026/10/20 新增**，只由 `SEQ RESUME`（重做模式）进入：
 *                            3 号抬到取样位上方(5000) → 2 号转到取样位 → 停 2 s
 *                            → 转入 `TASK_MOVE_POS` 子步骤 2，重做本任务的
 *                            取样/检测/抛弃。**不改 `Index`**，所以重做的就是当前任务；
 *                            做完后继续队列里剩余的任务。
 *                            与其它阶段不同，它是"从中间重新进入取样流程"的入口，
 *                            正常 `SEQ START` 永远不会经过它。
 *            TASK_PAUSE_PARK
 *                            **2026/10/27 新增**，只由 `SEQ PAUSE` 进入：
 *                            ① 已取样 → 先走 `TASK_DISCARD_POS` 回收（样品被处理掉）；
 *                            ② 3 号抬到安全高度(5000) → 2 号转到取样位正上方；
 *                            ③ 完成后才把 `SeqState` 置 `PAUSED`、黄灯慢闪、发事件帧。
 *                            归位期间 `SeqState` **保持 `RUNNING`**（否则状态机早退、
 *                            归位根本跑不起来），靠 `s_pauseRequested` / `s_pauseParked`
 *                            两个标志区分"正在归位"与"已停稳待恢复"。
 */
enum TaskPhase
{
    TASK_IDLE = 0,          ///< 任务空闲（准备进入本条任务）
    TASK_MOVE_POS,          ///< Ⅱ 取样位（KWQ1 原名"移动到 Axx"，这里复用）
    TASK_WAIT_RESISTOR_ACK, ///< 预留（KWQ1 电阻检测用，KWQ3 未使用）
    TASK_AUX_RUN,           ///< 预留（KWQ1 抽/推液与回位，KWQ3 未使用）
    TASK_PAUSED,            ///< 预留（KWQ3 用序列级 PAUSED 代替，未使用）
    TASK_END,               ///< 预留
    /* ---- 第三步新增（追加在末尾，不改动上面 6 个已实机验证的取值） ---- */
    TASK_PREAMBLE,          ///< 序列前导：2026/10/19 起不再动电机（零点由整机回零建立）
    TASK_TRAY_POS,          ///< 样品盘（4 号）定位到**本任务**的工位（MODE=1 绝对，取样之前）
    TASK_DETECT_POS,        ///< Ⅲ 检测位（3 号降到检测位后停留 T 分钟）
    TASK_DISCARD_POS,       ///< Ⅳ 回收位 / 抛弃位
    TASK_RESET_POS,         ///< 复位：3 号上升至 2000 → 2 号绝对定位回单圈回零原点 → 4 号样品盘接近开关回零（整条队列跑完时一次；2 号失败不中止只发 EVT 306，4 号失败中止并保留队列）
    TASK_RESTART_SAMPLE,    ///< **2026/10/20 新增**：`SEQ RESUME` 后丢弃断点，回取样位上方 → 停 2s → 从取样流程子步骤 2 重做本任务
    TASK_PAUSE_PARK         ///< **2026/10/27 新增**：暂停归位 —— 3 号抬到安全高度 → 2 号转到取样位正上方 → 停住并置 `PAUSED` 等 `SEQ RESUME`
};

