/**
 * @brief 创建任务序列执行常驻任务。
 * @details 必须在 `Rs485Devices_Init()` 之后、`EmmTaskQueue_Init()` 之后调用。
 *          任务创建后进入 10ms 周期轮询，序列未启动时每个周期立即返回，不会
 *          主动占用 RS485 总线；序列启动后每走一步都按 `Rs485Bus_Take()/
 *          Rs485Bus_Give()` 与其他设备共享总线。重复调用安全。
 * @return true 任务已启动或早已运行；false 任务创建失败。
 */
bool EmmTaskSeq_Init(void);

/**
 * @brief 序列是否正在执行（`RUNNING`）或已暂停（`PAUSED`）。
 * @details 供命令层做互锁判断，例如序列运行期间拒绝其它 EMM 动作命令。
 */
bool EmmTaskSeq_IsActive(void);

/**
 * @brief 取当前任务的执行阶段（仅用于诊断/日志）。
 */
TaskPhase EmmTaskSeq_GetPhase(void);

/**
 * @brief 执行阶段枚举转字符串（仅用于日志）。
 */
const char *EmmTaskSeq_TaskPhaseToStr(TaskPhase p);

/**
 * @brief 判断某条 EMM 命令在序列运行期间是否应被拒绝。
 * @details 与 `EmmSystemHome_BlocksCommand()` 同一套做法：序列运行期间独占
 *          机械机构，因此拦截所有会触发动作或修改电机状态的 `SET EMM *`
 *          命令（含 `SET EMM SYSTEM HOME`，避免序列中途被回零打断）；
 *          `GET EMM *` 查询、`SET EMM SYSTEM HOME STOP`、只切换本地布防
 *          标志的 `SET EMM LIFT MONITOR`，以及**只改内存变量 + 写 NVS、
 *          不产生总线事务**的 `SET EMM POINT` 始终放行。
 * @param commandName 已由 CommandDispatcher 匹配出的完整命令名。
 * @return true 表示应当拒绝；false 表示放行。
 */
bool EmmTaskSeq_BlocksCommand(const char *commandName);

/**
 * @brief 点位关系自检（**2026/10/21 新增**，供命令层调用）。
 * @details 检查 9 个运行期可改点位之间的**相对关系**是否合理（数值增大 = 下降）：
 *          `LIFT_S1 > SAFE`、`LIFT_S2 > LIFT_S1`、`SAFE < LIFT_DET < LIFT_S1`、
 *          `LIFT_D2 > SAFE`、`SAFE < LIFT_D3 < LIFT_D2`。
 *
 *          由 `cmdSetEmmPoint()` 在**序列运行中**改完点位后调用 —— 运行中改点位
 *          最容易改出"单值合法但关系不合理"（`LIFT_S2` 比 `LIFT_S1` 还浅，
 *          "慢降"会变成上升），而这时离下一次 `SEQ START` 还很久，开跑自检
 *          根本不会跑。
 * @note 只警告、不拒绝（与 `SEQ START` 前那次口径一致）：点位可能正处在
 *       "调一半"的中间态，硬拒会让人没法边跑边调。
 * @return true 关系全部合理；false 至少一条不合理（警告已由内部打印到串口）。
 */
bool EmmTaskSeq_CheckPoints(void);

/**
 * @brief 立即终止序列并清空队列（强制停止路径）。
 * @details 供 `SET POWER OFF`、指令超时休眠等"必须马上停下来"的路径调用，
 *          与上位机命令 `SEQ STOP` 共用同一套收尾逻辑，**顺序如下**：
 *            ① 置 `STOPPED`（先改状态，避免状态机把"Index/Count 同时归零"
 *               误判成"全部任务完成"）；
 *            ② 清空队列（`EmmTaskQueue_Clear()`）；
 *            ③ 复位执行状态机（`emmTaskSeqResetPhase()`）；
 *            ④ 黄灯待机（`RYG_COLOR_YELLOW`）；
 *            ⑤ **立即广播停止全部 EMM 电机**（`gEmm.stopBroadcast(false)`，
 *               2026/10/10 用户要求"命令一到就停，不等当前动作走完"）。
 *          幂等：序列本来就没跑时只打印日志，第 ⑤ 步照样发（重复一帧无害）。
 *
 * @note 为什么 `SET POWER OFF` 必须调它：断电时若只停电机而不管序列，
 *       `SeqState` 会一直停在 `RUNNING`，重新上电后 `SysInit` 又会去启动整机
 *       回零，于是"任务序列"和"初始化/回零"两套复合动作并行跑（实机已复现）。
 * @note 为什么第 ⑤ 步放在函数里而不是只靠序列任务轮询：序列任务可能正卡在
 *       同步步的静默间隔 / `vTaskDelay(1000)` 里不轮询状态，此时只有"命令一到
 *       就广播停机"才能立刻停住电机；等待循环里另有一道"停本步电机并等停稳"
 *       的兜底（见 `emmSeqHandlePauseResume()` 的中止分支）。
 */
void EmmTaskSeq_Stop(void);

/**
 * @brief 请求"结束当前任务"（`END CUR` 的内部入口，**2026/10/26 新增**）。
 * @details 与 `EmmTaskSeq_Stop()` 的区别是"**收尾式结束**"而不是"全丢"：
 *            ① **立即广播停止全部 EMM 电机**；
 *            ② 打断正在阻塞的那一步（`emmSeqHandlePauseResume()` 看到请求就停机退出）；
 *            ③ 执行**回收流程**（探头抬回安全高度）—— 但若此刻探头本来就在安全高度
 *               （`TASK_IDLE` / `TASK_PREAMBLE` / `TASK_TRAY_POS`），跳过回收省一趟空跑；
 *            ④ `Index++` 推进到下一条任务；
 *            ⑤ 若当前已是**最后一条**，转入**复位阶段**（3 号上升 → 2 号回单圈原点 →
 *               4 号样品盘重新标定），然后照常收尾（发 `EVT 300`、回 `STOPPED`、清队列）。
 *
 *          **不动 `SeqState`**：保持 `RUNNING`，用内部标志驱动，因为
 *          `emmTaskSeqRun()` 对非 `RUNNING` 直接返回、`emmSeqHandlePauseResume()`
 *          又把非 `RUNNING/PAUSED` 一律当中止 —— 改状态会把回收/复位这两步自己掐死。
 *
 * @return true 已受理；false 序列没在运行（幂等，无动作）。
 */
bool EmmTaskSeq_RequestEndCurrent(void);

/**
 * @brief 请求"结束全部任务"（`SEQ STOP` 的内部入口，**2026/10/26 新增**）。
 * @details **2026/10/27 起唯一调用方是 `cmdSeqStop()`**（原 `END ALL` 命令已删除，
 *          语义整体迁到 `SEQ STOP`）。
 *          与 `EmmTaskSeq_RequestEndCurrent()` 的差别只在 ④⑤：
 *            - 回收完成后**清空任务队列**（不推进到下一条）；
 *            - 直接进入**复位阶段**，复位完成后照常收尾。
 *          队列清空后 `Index >= Count` 自然成立，主循环的"队列已跑完"分支
 *          会自动把流程接到复位与收尾上，不需要额外的"结束态"。
 * @return true 已受理；false 序列没在运行（幂等，无动作）。
 */
bool EmmTaskSeq_RequestEndAll(void);

/**
 * @brief 上位机命令 `SEQ START`。
 * @details 前置检查顺序（任一失败立即回对应错误码，并打印失败原因）：
 *            ① 结构电源已合上      → 109 `NO_STEP_PWR`
 *            ② 序列未在运行        → 110 `SEQ_RUNNING`
 *            ③ 队列非空            → 103 `TASK_NULL`
 *            ④ 上位机心跳在线      → 115 `NO_HEARTBEAT`
 *            ⑤ 舱门已关闭          → 107 `NO_DOOR`
 *            ⑥ 样品盘已放置        → 105 `NO_SAMPLE`
 *            ⑦ 电机使能            → **注释占位，默认通过**（见 .cpp 内说明）
 *            ⑧ 控制板温度未超限    → 116 `TEMP_HIGH`
 *            ⑨ 整机已回零          → 104 `NO_HOME`
 *          全部通过后先进入 `TASK_PREAMBLE`（**2026/10/19 起该阶段不再动电机**：
 *          2/3 号零点由整机回零建立，序列不再重设），再进入第 1 条任务；
 *          立即回复 `OK @n SEQ START`，真正的动作在后台任务里跑。
 */
bool cmdSeqStart(const char *args, int seq);

/**
 * @brief 上位机命令 `SEQ PAUSE`（**2026/10/27 起改为"归位式暂停"**）。
 * @details 仅当序列处于 `RUNNING` 时接受，**立即回复** `OK @n SEQ PAUSE`；
 *          其它状态回 `ERR @n 110`（`SEQ_RUNNING`，语义为"序列状态不允许该操作"）。
 *
 *          **2026/10/27 起的新执行流程**（用户要求）：
 *            1. **电机动作立即停止**（命令侧先广播停机，不等轮询）；
 *            2. **已取到样**（`s_sampleTaken == true`）→ 先走完整**回收流程**
 *               （`TASK_DISCARD_POS`，10 个子步骤，样品在回收位被处理掉）；
 *               **未取到样** → 跳过回收；
 *            3. 归位到**取样位正上方**：3 号抬到安全高度 5000 → 2 号转到
 *               `SET EMM POINT SAMPLE`（默认 985）；即 `TASK_PAUSE_PARK`；
 *            4. 归位完成后才把 `SeqState` 置 `PAUSED`、黄灯慢闪，并发一帧
 *               `EVT 380 PAUSE PARKED`（`SEQ_PAUSE_PARKED`）告知上位机"可以恢复了"。
 *
 *          ⚠️ **归位期间 `SeqState` 保持 `RUNNING`**：`emmTaskSeqRun()` 对非 `RUNNING`
 *          直接早退，若在命令回调里立刻置 `PAUSED`，回收与归位这两步根本跑不起来。
 *          所以用 `s_pauseRequested`（待执行）与 `s_pauseParked`（已归位）两个标志，
 *          上位机侧看到的表现是"OK 立即返回，随后过若干秒才真正进入 PAUSED"。
 *
 *          ⚠️ **归位会丢弃样品**：回收位是处理样品的地方，不是放回托盘。所以恢复
 *          （`SEQ RESUME`）后**必然重做当前任务**（重新取样、检测位停留重新计时），
 *          不存在"从断点续跑"。
 */
bool cmdSeqPause(const char *args, int seq);

/**
 * @brief 上位机命令 `SEQ RESUME`（**2026/10/27 起无参数，只有"重做"一种语义**）。
 * @details 仅当序列处于 `PAUSED` 时接受；其它状态回 `ERR @n 110`。
 *          接受前会复查舱门与样品盘（对齐 KWQ1 在恢复时复查限位的行为，防止暂停期间
 *          开门/取盘后被带着继续跑）。
 *
 *          **参数：无。** `MODE` 已整体移除（用户要求"序列恢复命令不需要 MODE，
 *          只需要 `SEQ RESUME`，因为当前恢复只有一种方式了"）。
 *
 *          | 命令 | 语义 | 应答 |
 *          | ---- | ---- | ---- |
 *          | `SEQ RESUME` | **重做**当前任务：从取样位重新取样 → 检测 → 回收 → 继续剩余任务 | `OK @n SEQ RESUME` |
 *          | `SEQ RESUME MODE=0` / `MODE=1` | **参数已废弃**，按上面的重做执行（串口打印一行提示） | `OK @n SEQ RESUME` |
 *
 *          **为什么不再有"续跑"**：`SEQ PAUSE` 会把已取的样品回收掉、把探头归位到
 *          取样位正上方，断点位置与样品都不存在了 —— "重发本步命令从断点继续"
 *          等于让探头在安全高度上假装还在原位置做绝对定位，后续每一步的相对动作全错位。
 *
 *          **老上位机兼容**：带 `MODE=` 不报错（**不再回 `ERR 102`**），只是忽略参数，
 *          应答格式也不再回显 `MODE=`。这样现场不必同步升级上位机。
 *
 *          **`Index` 不变**，所以重做的就是当前这条任务；做完继续队列里剩余的任务，
 *          全部跑完后再进复位（复位流程本身不变）。
 */
bool cmdSeqResume(const char *args, int seq);

/**
 * @brief 上位机命令 `SEQ STOP`（**2026/10/27 起接管"结束全部"语义**）。
 * @details 语义（用户 2026/10/27 指定，即原 `END ALL` 的行为）：
 *            电机动作立即停止 → 结束全部任务 → **执行回收流程** → **清空任务队列**
 *            → **执行复位流程**（3 号上升至 2000 → 2 号回单圈原点 → 4 号接近开关回零）
 *            → 收尾（`EVT 300 SEQ ALL DONE` + `STOPPED` + 黄灯待机）。
 *
 *          与"急停"（`ESTOP`）的分工：
 *
 *          | | `SEQ STOP` | `ESTOP` |
 *          | --- | --- | --- |
 *          | 电机 | 立即广播停止 | 立即广播停止 |
 *          | 探头 | **按回收流程抬回安全高度** | **停在原地**（可能留在样品里） |
 *          | 队列 | 清空 | 清空 |
 *          | 复位 | 做 | 不做 |
 *          | 是否动电机 | **要动** → 断电时回 `ERR 109` | 不动 → 任何时候可用 |
 *
 *          应答：
 *            - 结构电源未接通 → `ERR @n 109`（`NO_STEP_PWR`），此时应改用 `ESTOP`；
 *            - 其余情况（含序列未在运行）→ `OK @n SEQ STOP`（幂等，无动作）。
 *          受理后实际动作在后台任务里完成，进度看串口日志与事件帧。
 *
 *          ⚠️ **不再是"始终回 OK"**：2026/10/10 版本因为不动电机所以可以无条件回 OK；
 *          现在要动电机做回收与复位，断电时必须拒绝，否则会给上位机"已停止"的错觉。
 */
bool cmdSeqStop(const char *args, int seq);

/**
 * @brief 上位机命令 `END CUR`（结束当前任务，**2026/10/26 新增**）。
 * @details 语义：电机动作立即停止 → 结束当前任务 → 回收流程 → 执行下一个任务；
 *          若当前是最后一条，则执行任务阶段的复位流程。
 *          应答：
 *            - 结构电源未接通 → `ERR @n 109`（`NO_STEP_PWR`）；
 *            - 其余情况（含序列未在运行）→ `OK @n END CUR`（幂等，无动作）。
 *          实际动作在后台任务里完成，受理后不再回复中间帧；若走到收尾仍发 `EVT 300`。
 */
bool cmdEndCur(const char *args, int seq);

/**
 * @brief 上位机命令 `ESTOP`（急停，**2026/10/27 新增**）。
 * @details 语义 = 原 `SEQ STOP` 的行为（用户要求"原有的停止逻辑迁移到急停命令上"）：
 *          立即广播停止全部 EMM 电机 → 清空任务队列 → `SeqState` 置 `STOPPED` →
 *          复位执行状态机 → 黄灯待机。**不做回收、不做复位、探头停在原地。**
 *
 *          **2026/10/27 追加（用户拍板）**：`ESTOP` = "**全量复位，但不断结构电源**"，
 *          与 `SET POWER OFF`（`sysPowerOffCleanup()`）的差别只剩"不切电源"这一条：
 *            - 额外调 `EmmSystemHome_RequestStop()` —— 中止正在跑的**整机回零**
 *              （不中止的话急停只停了"这一帧"，回零下一步会继续发命令）；
 *            - 额外调 `SysInit_Abort()` —— 中止**系统初始化**（其本质就是启动整机回零）；
 *            - 额外清 `sys_is_homed = false` —— **零点失效**，急停后 `SEQ START`
 *              回 `104 NO_HOME`，必须先 `SET EMM SYSTEM HOME` 重新回零。
 *
 *          ⚠️ `s_emmHomeBusy` / `s_sysInitBusy` **不在这里强制清零**（只能由各自的
 *          流程任务收尾），所以急停后立刻发 `SET EMM SYSTEM HOME` 可能回 `110`，
 *          等几秒（回零任务走到检查点）即可。
 *
 *          **任何状态都接受、永不拒绝**（包括结构电源已断）：
 *            - 只发停止帧 + 清状态，断电时发不出去也只打印警告；
 *            - 序列本来就没跑时是空操作，仍回 `OK`；
 *            - 这是唯一的"无条件可用"的停止命令。
 *
 *          **急停后恢复生产的完整步骤**：
 *            `SET POWER ON`（若已断电）→ `SET EMM SYSTEM HOME` 重新回零 →
 *            `SEQ ADD …` 重新编队 → `SEQ START`。
 *
 *          应答：始终 `OK @n ESTOP`。
 */
bool cmdEstop(const char *args, int seq);

